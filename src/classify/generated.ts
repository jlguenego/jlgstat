// Generated-file detection (§5.5.1): path/name rules, header markers and
// minification. Header checks reuse the buffer already read for binary sniffing.

const GENERATED_NAMES = new Set([
  'package-lock.json',
  'npm-shrinkwrap.json',
  'pnpm-lock.yaml',
  'yarn.lock',
  'poetry.lock',
  'cargo.lock',
  'composer.lock',
  'gemfile.lock',
  'go.sum',
]);

const GENERATED_NAME_PATTERNS: readonly RegExp[] = [
  /\.min\.js$/,
  /\.min\.css$/,
  /\.map$/,
  /\.lock$/,
  /\.generated\./,
  /\.g\.dart$/,
  /\.pb\.go$/,
  /_pb2\.py$/,
  /\.designer\.cs$/,
];

const GENERATED_DIRS = new Set(['__snapshots__', '__generated__']);

/** Path-based rule. `dirs` and `name` are lowercase. */
export function isGeneratedByPath(dirs: readonly string[], name: string): boolean {
  if (GENERATED_NAMES.has(name)) return true;
  if (GENERATED_NAME_PATTERNS.some((re) => re.test(name))) return true;
  return dirs.some((d) => GENERATED_DIRS.has(d));
}

const HEADER_MARKERS: readonly RegExp[] = [
  /code generated.*do not edit/i,
  /@generated/i,
  /<auto-generated/i,
  /this file is automatically generated/i,
  /(?:autogenerated|generated) by.*(?:protoc|openapi|swagger|graphql-codegen|prisma|thrift|sqlc)/i,
];

const HEADER_LINES = 5;
const HEADER_MARKER_CHARS = 1024;
const MINIFIED_LINE_CHARS = 1000;

function firstLines(text: string, count: number): string[] {
  const lines: string[] = [];
  let start = 0;
  while (lines.length < count && start <= text.length) {
    const lf = text.indexOf('\n', start);
    const cr = text.indexOf('\r', start);
    let end = lf === -1 ? cr : cr === -1 ? lf : Math.min(lf, cr);
    if (end === -1) {
      if (start < text.length) lines.push(text.slice(start));
      break;
    }
    lines.push(text.slice(start, end));
    if (text.charCodeAt(end) === 13 && text.charCodeAt(end + 1) === 10) end++;
    start = end + 1;
  }
  return lines;
}

/** Header marker rule: searched in the first 5 lines and at most 1 kB. */
export function hasGeneratedMarker(header: string): boolean {
  const lines = firstLines(header.slice(0, HEADER_MARKER_CHARS), HEADER_LINES);
  return lines.some((line) => HEADER_MARKERS.some((re) => re.test(line)));
}

/** Minification rule: a line over 1,000 characters among the first 5 lines. */
export function looksMinified(header: string): boolean {
  return firstLines(header, HEADER_LINES).some((line) => line.length > MINIFIED_LINE_CHARS);
}
