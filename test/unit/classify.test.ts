import { describe, expect, test } from 'bun:test';
import { classify } from '../../src/classify/category.js';
import { extensionOf, NO_EXTENSION } from '../../src/classify/extension.js';
import { sniff } from '../../src/read/sniff.js';
import type { Category, FileKind } from '../../src/report/model.js';
import { detectLanguage } from '../../src/syntax/languages.js';

describe('extensions (§4.3)', () => {
  test.each([
    ['App.TS', '.ts'],
    ['index.d.ts', '.ts'],
    ['a.test.ts', '.ts'],
    ['.gitignore', NO_EXTENSION],
    ['.env', NO_EXTENSION],
    ['Makefile', NO_EXTENSION],
    ['.eslintrc.json', '.json'],
    ['archive.tar.gz', '.gz'],
    ['trailing.', NO_EXTENSION],
  ])('%s → %s', (name, ext) => {
    expect(extensionOf(name)).toBe(ext);
  });
});

const cat = (path: string, kind: FileKind = 'text', header: string | null = ''): Category => {
  const name = path.slice(path.lastIndexOf('/') + 1);
  const extension = extensionOf(name);
  return classify({ path, extension, kind, language: detectLanguage(name, extension), header: kind === 'text' ? header : null });
};

describe('categories (§5.5)', () => {
  test.each<[string, Category]>([
    ['src/app.ts', 'sources'],
    ['src/styles/site.css', 'sources'],
    ['scripts/deploy.sh', 'sources'],
    ['db/schema.sql', 'sources'],
    ['src/app.min.js', 'generated'],
    ['package-lock.json', 'generated'],
    ['yarn.lock', 'generated'],
    ['go.sum', 'generated'],
    ['src/__generated__/types.ts', 'generated'],
    ['src/__snapshots__/a.test.ts.snap', 'generated'],
    ['api/service.pb.go', 'generated'],
    ['tests/unit/a.ts', 'tests'],
    ['src/a.test.ts', 'tests'],
    ['src/a.spec.js', 'tests'],
    ['pkg/a_test.go', 'tests'],
    ['test_app.py', 'tests'],
    ['src/FooTest.java', 'tests'],
    ['src/Latest.java', 'sources'],
    ['spec/fixtures/data.json', 'tests'],
    ['README.md', 'documentation'],
    ['LICENSE', 'documentation'],
    ['CHANGELOG', 'documentation'],
    ['docs/diagram.ts', 'documentation'],
    ['package.json', 'configuration'],
    ['tsconfig.build.json', 'configuration'],
    ['vite.config.ts', 'configuration'],
    ['.eslintrc.json', 'configuration'],
    ['.npmrc', 'configuration'],
    ['.env.local', 'configuration'],
    ['Dockerfile', 'configuration'],
    ['Makefile', 'configuration'],
    ['.github/workflows/ci.yml', 'configuration'],
    ['config/settings.yaml', 'configuration'],
    ['src/locales/en.json', 'other'],
    ['public/data.xml', 'other'],
    ['data/table.csv', 'other'],
    ['notes.unknownext', 'other'],
  ])('%s → %s', (path, expected) => {
    expect(cat(path)).toBe(expected);
  });

  test('binaries are unknown unless a path rule matches', () => {
    expect(cat('img/logo.png', 'binary')).toBe('unknown');
    expect(cat('docs/logo.png', 'binary')).toBe('documentation');
    expect(cat('tests/fixtures/a.bin', 'binary')).toBe('tests');
  });

  test('header markers and minification mark generated files', () => {
    expect(cat('src/a.go', 'text', '// Code generated by mockgen. DO NOT EDIT.\npackage a')).toBe('generated');
    expect(cat('src/a.ts', 'text', '/* @generated */')).toBe('generated');
    expect(cat('src/a.cs', 'text', '// <auto-generated>\n')).toBe('generated');
    expect(cat('src/a.ts', 'text', '// Generated by graphql-codegen\n')).toBe('generated');
    expect(cat('src/a.js', 'text', `var a=1;${'x'.repeat(1001)}`)).toBe('generated');
    expect(cat('src/a.ts', 'text', 'a\nb\nc\nd\ne\n// @generated')).toBe('sources');
    expect(cat('data/big.csv', 'text', 'x'.repeat(5000))).toBe('other');
  });

  test('comparisons are case-insensitive', () => {
    expect(cat('Tests/A.ts')).toBe('tests');
    expect(cat('PACKAGE-LOCK.JSON')).toBe('generated');
  });
});

describe('binary and encoding detection (§4.4)', () => {
  const s = (bytes: number[] | Buffer, truncated = false) => {
    const b = Buffer.isBuffer(bytes) ? bytes : Buffer.from(bytes);
    return sniff(b, b.length, truncated);
  };

  test('text encodings', () => {
    expect(s(Buffer.from('hello'))).toEqual({ binary: false, encoding: 'utf-8' });
    expect(s(Buffer.from('héllo'))).toEqual({ binary: false, encoding: 'utf-8' });
    expect(s([0xef, 0xbb, 0xbf, 0x61])).toEqual({ binary: false, encoding: 'utf-8-bom' });
    expect(s([0xff, 0xfe, 0x61, 0x00])).toEqual({ binary: false, encoding: 'utf-16le' });
    expect(s([0xfe, 0xff, 0x00, 0x61])).toEqual({ binary: false, encoding: 'utf-16be' });
    expect(s(Buffer.from('caf\xe9', 'latin1'))).toEqual({ binary: false, encoding: 'unknown-8bit' });
    expect(s(Buffer.alloc(0))).toEqual({ binary: false, encoding: 'utf-8' });
  });

  test('a UTF-8 sequence cut by the sniff window stays UTF-8', () => {
    const b = Buffer.from('aé');
    expect(s(b.subarray(0, 2), true)).toEqual({ binary: false, encoding: 'utf-8' });
  });

  test('binaries', () => {
    expect(s([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a]).binary).toBe(true);
    expect(s(Buffer.from('abc\0def')).binary).toBe(true);
    expect(s(Buffer.from([1, 2, 3, 4, 5, 6, 0x61])).binary).toBe(true);
  });
});
